#!/usr/bin/env python3
"""Build a single-file `.pyz` artifact of the probe with a real hub URL baked in.

Usage:
    python3 probe/build_pyz.py --hub-url http://<vps-ip>:8100 [--token TOKEN] [-o dist/probe.pyz]

This is a dev-time tool, not something that ships. It:
  1. Copies `probe/src` (the package root) into a temp staging directory,
     excluding `__pycache__`, `*.egg-info`, and `*.pyc` cruft.
  2. Overwrites the staged `probe/_defaults.py` with plain literal assignments
     for DEFAULT_HUB_URL, DEFAULT_TOKEN, and VERSION (no fallback logic needed
     once baked into a zipapp -- the values are no longer ambiguous).
  3. Zips the staging directory into a `.pyz` with `probe.cli:main` as the
     entry point, so the result is runnable as `python3 probe.pyz [...]`.

Never bake a real hub URL or token into anything committed to the repo --
this script only writes to `dist/`, which is gitignored, or to an explicit
`-o/--output` path the caller chooses.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import tempfile
import zipapp
from pathlib import Path

PROBE_DIR = Path(__file__).resolve().parent          # .../probe
REPO_ROOT = PROBE_DIR.parent                          # repo root
PROBE_SRC_DIR = PROBE_DIR / "src"                     # .../probe/src (contains the probe/ package)
PYPROJECT_PATH = PROBE_DIR / "pyproject.toml"
DEFAULT_OUTPUT = REPO_ROOT / "dist" / "probe.pyz"


def read_dotenv(key: str) -> str | None:
    """Read a single KEY from the repo-root .env, or None if absent.

    Deliberately tiny (no python-dotenv dep): the probe stays stdlib-only and
    this is a dev-time build tool. Handles `KEY=value`, skips blanks/comments,
    strips surrounding quotes, and ignores an optional `export ` prefix.
    """
    env_path = REPO_ROOT / ".env"
    try:
        lines = env_path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return None
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].lstrip()
        name, sep, value = line.partition("=")
        if sep and name.strip() == key:
            return value.strip().strip('"').strip("'")
    return None


def read_version() -> str:
    """Read [project].version from probe/pyproject.toml using tomllib (3.11+)."""
    try:
        import tomllib
    except ImportError as exc:
        raise SystemExit(
            "error: build_pyz.py requires Python 3.11+ (needs stdlib `tomllib` to read "
            f"{PYPROJECT_PATH}). The built probe.pyz itself still only requires the "
            "probe package's own Python 3.10+ floor -- only this build script needs a "
            "newer interpreter."
        ) from exc

    try:
        data = tomllib.loads(PYPROJECT_PATH.read_text(encoding="utf-8"))
    except OSError as exc:
        raise SystemExit(f"error: could not read {PYPROJECT_PATH}: {exc}") from exc

    version = data.get("project", {}).get("version")
    if not version:
        raise SystemExit(f"error: no [project].version found in {PYPROJECT_PATH}")
    return str(version)


def assert_no_cruft(root: Path) -> None:
    """Belt-and-suspenders check: fail loudly if ignore_patterns somehow missed cruft."""
    offenders = [
        p
        for p in root.rglob("*")
        if p.is_dir() and (p.name == "__pycache__" or p.name.endswith(".egg-info"))
    ]
    if offenders:
        joined = "\n".join(f"  - {p}" for p in offenders)
        raise SystemExit(
            "error: staged tree still contains cruft that should have been excluded:\n"
            f"{joined}"
        )


def write_defaults(defaults_path: Path, hub_url: str, token: str, version: str) -> None:
    content = (
        '"""Shared default constants for the probe CLI.\n'
        "\n"
        "Generated by build_pyz.py -- baked for a specific deployment, not for source control.\n"
        '"""\n'
        "\n"
        f"DEFAULT_HUB_URL = {hub_url!r}\n"
        f"DEFAULT_TOKEN = {token!r}\n"
        f"VERSION = {version!r}\n"
    )
    defaults_path.write_text(content, encoding="utf-8")


def build(hub_url: str, token: str, output: Path) -> Path:
    version = read_version()

    output = output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="probe-pyz-") as tmp:
        stage_src = Path(tmp) / "src"
        shutil.copytree(
            PROBE_SRC_DIR,
            stage_src,
            ignore=shutil.ignore_patterns("__pycache__", "*.egg-info", "*.pyc"),
        )

        assert_no_cruft(stage_src)

        defaults_path = stage_src / "probe" / "_defaults.py"
        if not defaults_path.is_file():
            raise SystemExit(f"error: expected {defaults_path} to exist after copytree, but it's missing")
        write_defaults(defaults_path, hub_url, token, version)

        # stage_src directly contains the `probe/` package -> this is the zipapp root,
        # so the archive's top-level layout is `probe/...` and `main="probe.cli:main"`
        # resolves correctly.
        if output.exists():
            output.unlink()
        zipapp.create_archive(
            source=stage_src,
            target=output,
            interpreter="/usr/bin/env python3",
            main="probe.cli:main",
        )

    return output


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build a single-file probe.pyz with a real hub URL (and optional token) baked in."
    )
    parser.add_argument(
        "--hub-url",
        default=None,
        help="hub base URL to bake in as DEFAULT_HUB_URL "
        "(default: PROBEHUB_URL from the repo-root .env)",
    )
    parser.add_argument(
        "--token",
        default=None,
        help="hub API token to bake in as DEFAULT_TOKEN "
        "(default: PROBEHUB_TOKEN from .env, else empty)",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"output .pyz path (default: {DEFAULT_OUTPUT})",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    # --hub-url wins; otherwise fall back to PROBEHUB_URL in the repo-root .env.
    hub_url = args.hub_url or read_dotenv("PROBEHUB_URL")
    if not hub_url:
        raise SystemExit(
            "error: no hub URL. Pass --hub-url, or set PROBEHUB_URL in the repo-root .env"
        )

    # --token wins (including an explicit empty ""); else PROBEHUB_TOKEN; else empty.
    token = args.token if args.token is not None else (read_dotenv("PROBEHUB_TOKEN") or "")

    print(f"baking hub URL: {hub_url}" + ("  (+token)" if token else "  (no token)"))
    output = build(hub_url, token, args.output)
    size = output.stat().st_size
    print(f"built {output} ({size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
